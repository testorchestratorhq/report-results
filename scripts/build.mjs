// Bundles src/main.ts and its dependencies into dist/index.js (one file, no node_modules at runtime).
// `--check` rebuilds in memory and fails when the committed dist/ differs from the source (the CI check).
import { build } from 'esbuild'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const check = process.argv.includes('--check')
const result = await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  outfile: 'dist/index.js',
  write: false,
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/build.mjs from src/ - do not edit. https://github.com/testorchestratorhq/report-results',
  },
})
const out = result.outputFiles[0].text.replace(/\r\n/g, '\n')
let current
try {
  current = readFileSync('dist/index.js', 'utf8')
} catch {
  current = null
}
if (check) {
  if (current !== out) {
    console.error('dist/index.js is not the build of src/: run npm run build and commit dist/')
    process.exit(1)
  }
  console.log(`dist/index.js matches the source (${out.length} bytes)`)
} else {
  mkdirSync('dist', { recursive: true })
  if (current !== out) writeFileSync('dist/index.js', out)
  console.log(`dist/index.js ${out.length} bytes`)
}
